export type EditorLine = {
  /** Stable while editing (server line ids change on every save). */
  key: string
  description: string
  quantity: string
  unit: Unit | null
  unit_price: string
  discount_percent: string
  vat_category: VatCategory
  vat_rate: string
  /** Sent only for EXEMPTION_CATEGORIES. */
  vat_exemption_code: string | null
  vat_exemption_reason: string
  /** A catalogue item priced in another currency: its price stays empty until typed in the invoice's. */
  price_currency?: string
}

export type EditorValues = {
  /** Fixed for the document: sent once, on create. */
  kind: InvoiceKind
  client_id: string | null
  issue_date: string
  due_date: string
  service_date: string
  service_date_end: string
  currency: string
  language: DocLanguage
  vat_mode: VatMode
  reference: string
  /** null: the client's Helvetly number is printed; '': no client number; else this text instead. */
  client_number_display: string | null
  /** The contract the invoice refers to, printed and sent in e-invoices (BT-12). */
  contract_reference: string
  /** A contract in Documents linked to the invoice (never printed). */
  contract_document: { id: string; name: string } | null
  /** RON per unit of the currency (RO e-Factura); used only while needsRonRate holds. */
  tax_currency_rate: string
  intro: string
  footer: string
  note: string
  discount_percent: string
  lines: EditorLine[]
  /** As chosen; the QR bill is only sent for CHF and EUR (see toInput). */
  payment_methods: PaymentMethods
  /** Kind invoice only: the prepayment invoices this final invoice deducts. */
  prepayments: Invoice['prepayments']
  /** Receivable kinds only; null: paid at once. */
  instalments: EditorInstalments | null
  reminders_enabled: boolean
}

export type InstalmentRow = { due_date: string; amount: string }
export type EditorInstalments = {
  count: string
  interval: Interval
  first_due_date: string
  /** null: generated by the server from the amount due on every save; else as typed. */
  items: InstalmentRow[] | null
}

/** Field errors: top-level names ("due_date") or "<line key>.<field>". */
export type EditorErrors = Record<string, string>

let counter = 0
export const lineKey = () => `line-${Date.now().toString(36)}-${(counter += 1)}`

export function newLine(values: Pick<EditorValues, 'vat_mode'>, defaultRate: string): EditorLine {
  return {
    key: lineKey(),
    description: '',
    quantity: '1',
    unit: null,
    unit_price: '',
    discount_percent: '',
    vat_category: values.vat_mode === 'none' ? 'O' : 'S',
    vat_rate: values.vat_mode === 'none' ? '0' : defaultRate,
    vat_exemption_code: values.vat_mode === 'none' ? defaultExemptionCode('O') : null,
    vat_exemption_reason: '',
  }
}

const termsOf = (client: Pick<Client, 'payment_terms_days'> | null, settings: InvoiceSettings) =>
  client?.payment_terms_days ?? settings.default_terms_days

/** A new document: the workspace defaults, then the client's when one is given. */
export function emptyValues(
  settings: InvoiceSettings,
  client: Client | null = null,
  kind: InvoiceKind = 'invoice',
): EditorValues {
  const issue = today()
  const vatMode = settings.vat_registered ? settings.default_vat_mode : 'none'
  const values: EditorValues = {
    kind,
    client_id: null,
    issue_date: issue,
    due_date: addDays(issue, settings.default_terms_days),
    service_date: '',
    service_date_end: '',
    currency: settings.currency,
    language: settings.language,
    vat_mode: vatMode,
    reference: '',
    client_number_display: null,
    contract_reference: '',
    contract_document: null,
    tax_currency_rate: '',
    intro: '',
    footer: settings.footer ?? '',
    note: '',
    discount_percent: '',
    lines: [],
    payment_methods: defaultPaymentMethods(settings, settings.currency),
    prepayments: [],
    instalments: null,
    reminders_enabled: settings.instalments.reminders_enabled,
  }
  values.lines = [newLine(values, settings.default_vat_rate)]
  return client ? applyClient(values, client, settings) : values
}

/** Picking a client brings its currency, language and payment terms. */
export function applyClient(
  values: EditorValues,
  client: Client,
  settings: InvoiceSettings,
): EditorValues {
  return {
    ...values,
    client_id: client.id,
    currency: client.currency ?? settings.currency,
    language: client.language ?? settings.language,
    due_date: addDays(values.issue_date, termsOf(client, settings)),
  }
}

const decimalText = (value: string) => (/^0*(\.0*)?$/.test(value) ? '' : value)
const trimFractionZeros = (value: string) =>
  value.includes('.') ? value.replace(/\.?0+$/, '') || '0' : value

/** A saved line as typed in the editor (quotes share the invoice line). */
export const editorLine = (line: Line): EditorLine => ({
  key: lineKey(),
  description: line.description,
  quantity: trimFractionZeros(line.quantity),
  unit: line.unit,
  unit_price: line.unit_price,
  discount_percent: decimalText(line.discount_percent),
  vat_category: line.vat_category,
  vat_rate: trimFractionZeros(line.vat_rate),
  vat_exemption_code: line.vat_exemption_code,
  vat_exemption_reason: line.vat_exemption_reason ?? '',
})

export function valuesFromInvoice(invoice: Invoice, defaultRate: string): EditorValues {
  const values: EditorValues = {
    kind: invoice.kind,
    client_id: invoice.client_id,
    issue_date: invoice.issue_date,
    due_date: invoice.due_date,
    service_date: invoice.service_date ?? '',
    service_date_end: invoice.service_date_end ?? '',
    currency: invoice.currency,
    language: invoice.language,
    vat_mode: invoice.vat_mode,
    reference: invoice.reference ?? '',
    client_number_display: invoice.client_number_display,
    contract_reference: invoice.contract_reference ?? '',
    contract_document: invoice.contract_document,
    tax_currency_rate: invoice.tax_currency_rate ?? '',
    intro: invoice.intro ?? '',
    footer: invoice.footer ?? '',
    note: invoice.note ?? '',
    payment_methods: invoice.payment_methods,
    prepayments: invoice.prepayments,
    instalments: editorInstalments(invoice),
    reminders_enabled: invoice.reminders_enabled,
    discount_percent: decimalText(invoice.discount_percent),
    lines: invoice.lines.map(editorLine),
  }
  // A document always shows a line to type into, even one saved without lines.
  if (values.lines.length === 0) values.lines = [newLine(values, defaultRate)]
  return values
}

/** A line nobody has started: it is neither saved nor validated. */
export const isBlankLine = (line: EditorLine) => !line.description.trim() && !line.unit_price.trim()

const orNull = (text: string) => text.trim() || null

type Converted = { input: Partial<InvoiceInput>; errors: EditorErrors; keys: string[] }

/**
 * The contract's input for the values, the number fields' errors (keyed for the editor), and the
 * line keys in the order they were sent (to map the server's `lines.N.field` errors back).
 * `forPreview` sends every line, blank ones too, so the amounts line up with the rows.
 */
/** The largest unit price the API accepts (100'000'000.00). */
const MAX_PRICE = 100_000_000

export function toInput(values: EditorValues, forPreview = false): Converted {
  const errors: EditorErrors = {}
  const keys: string[] = []
  const lines: LineInput[] = []
  for (const line of values.lines) {
    if (!forPreview && isBlankLine(line)) continue
    const quantity = parseDecimalInput(line.quantity || '0', 3)
    const price = parseDecimalInput(line.unit_price || '0', 2, true)
    const discount = parseDecimalInput(line.discount_percent || '0', 2)
    const rate = parseDecimalInput(line.vat_rate || '0', 2)
    if (quantity === null || quantity.startsWith('-'))
      errors[`${line.key}.quantity`] = translate('aNumberLike1Or25')
    if (price === null || price.startsWith('-'))
      errors[`${line.key}.unit_price`] = translate('aPriceLike12000')
    // The API's limit: a larger price is refused, also by the totals preview.
    else if (Number(price) > MAX_PRICE) errors[`${line.key}.unit_price`] = translate('priceAtMost')
    if (discount === null || discount.startsWith('-') || Number(discount) > 100)
      errors[`${line.key}.discount_percent`] = translate('from0To100')
    if (rate === null || Number(rate) > 100)
      errors[`${line.key}.vat_rate`] = translate('from0To100')
    if (!forPreview && line.price_currency && !line.unit_price.trim())
      errors[`${line.key}.unit_price`] = translate('enterThePrice', { currency: values.currency })
    const category = values.vat_mode === 'none' ? 'O' : line.vat_category
    const exempt = EXEMPTION_CATEGORIES.includes(category)
    const reason = exempt ? orNull(line.vat_exemption_reason) : null
    if (reason && reason.length > 300)
      errors[`${line.key}.vat_exemption_reason`] = translate('atMost300Characters')
    keys.push(line.key)
    lines.push({
      description: line.description.trim(),
      quantity: quantity ?? '0',
      unit: line.unit,
      unit_price: price ?? '0.00',
      discount_percent: discount ?? '0',
      vat_category: category,
      vat_rate: category !== 'S' ? '0' : (rate ?? '0'),
      vat_exemption_code: exempt ? line.vat_exemption_code : null,
      vat_exemption_reason: reason,
    })
  }
  const discount = parseDecimalInput(values.discount_percent || '0', 2)
  const schedule = forPreview ? previewInstalments(values) : instalmentInput(values, errors)
  if (discount === null || discount.startsWith('-') || Number(discount) > 100)
    errors.discount_percent = translate('from0To100')
  return {
    errors,
    keys,
    input: {
      ...(values.client_id ? { client_id: values.client_id } : {}),
      issue_date: values.issue_date,
      due_date: values.due_date,
      service_date: orNull(values.service_date),
      service_date_end: values.service_date ? orNull(values.service_date_end) : null,
      currency: values.currency,
      language: values.language,
      vat_mode: values.vat_mode,
      reference: orNull(values.reference),
      client_number_display: values.client_number_display,
      contract_reference: orNull(values.contract_reference),
      contract_document_id: values.contract_document?.id ?? null,
      tax_currency_rate: orNull(values.tax_currency_rate),
      intro: orNull(values.intro),
      footer: orNull(values.footer),
      note: orNull(values.note),
      discount_percent: discount ?? '0',
      lines,
      // As chosen; the editor passes only usable methods (usableMethods).
      payment_methods: values.payment_methods,
      ...(values.kind === 'invoice'
        ? { prepayment_ids: values.prepayments.map((prepayment) => prepayment.id) }
        : {}),
      ...(schedule === undefined
        ? {}
        : { instalments: schedule, reminders_enabled: values.reminders_enabled }),
    },
  }
}

/** The schedule without its rows, so the preview answers the rows the server would generate. */
function previewInstalments(values: EditorValues): InstalmentInput | undefined {
  const schedule = values.instalments
  const count = Number(schedule?.count)
  if (!schedule || !isReceivable(values.kind) || !schedule.first_due_date) return undefined
  if (!Number.isInteger(count) || count < 2 || count > 12) return undefined
  return { count, interval: schedule.interval, first_due_date: schedule.first_due_date }
}

/** The schedule as sent (undefined for kinds that cannot have one), its field errors into `errors`. */
function instalmentInput(values: EditorValues, errors: EditorErrors) {
  if (!isReceivable(values.kind)) return undefined
  const schedule = values.instalments
  if (!schedule) return null
  const count = Number(schedule.count)
  if (!/^\d{1,2}$/.test(schedule.count) || count < 2 || count > 12)
    errors['instalments.count'] = translate('from2To12')
  const items = schedule.items?.map((item, i) => {
    const amount = parseDecimalInput(item.amount, 2, true)
    if (amount === null || !/^\d/.test(amount) || /^0*\.?0*$/.test(amount))
      errors[`instalments.items.${i}.amount`] = translate('anAmountLike36035')
    return { due_date: item.due_date, amount: amount ?? '0.00' }
  })
  return {
    count,
    interval: schedule.interval,
    first_due_date: schedule.first_due_date,
    ...(items ? { items } : {}),
  }
}

/** How far the rows are from the amount due ("39.65"), or null when they match or cannot be read. */
export function instalmentGap(rows: InstalmentRow[], amountDue: string): string | null {
  let sum = 0n
  for (const row of rows) {
    const amount = parseDecimalInput(row.amount, 2, true)
    if (amount === null) return null
    sum += toCents(amount)
  }
  const gap = toCents(amountDue) - sum
  return gap === 0n ? null : fromCents(gap < 0n ? -gap : gap)
}

/** A new schedule from the workspace defaults, the first instalment due on `firstDue`. */
export const startInstalments = (
  settings: InvoiceSettings,
  firstDue: string,
): EditorInstalments => ({
  count: String(settings.instalments.count),
  interval: settings.instalments.interval,
  first_due_date: firstDue,
  items: null,
})

/** The footer's one line for a schedule: "3× · Monthly · from 1 Dec 2026"; the rows as typed win over the shape. */
export function instalmentsSummary(schedule: EditorInstalments): string {
  const interval = INTERVALS.find((entry) => entry.value === schedule.interval)?.label ?? ''
  const first = schedule.items?.[0]?.due_date ?? schedule.first_due_date
  return translate('instalmentsSummary', {
    count: schedule.items?.length ?? schedule.count,
    interval,
    date: first ? formatDay(first) : '—',
  })
}

/** A saved schedule (an invoice's or a quote's) as typed; the editor makes it generated again when it equals the preview's. */
export function editorInstalments(doc: Pick<Invoice, 'instalments'>): EditorInstalments | null {
  const schedule = doc.instalments
  const first = schedule?.items[0]
  if (!schedule || !first) return null
  return {
    count: String(schedule.items.length),
    interval: schedule.interval,
    first_due_date: first.due_date,
    items: schedule.items.map(({ due_date, amount }) => ({ due_date, amount })),
  }
}

/** What the deducted prepayments add up to, gross. */
export const prepaidTotal = (
  prepayments: Pick<Invoice['prepayments'][number], 'payable_total'>[],
) => fromCents(prepayments.reduce((sum, prepayment) => sum + toCents(prepayment.payable_total), 0n))

/** The server's 422 fields mapped onto the editor ("lines.2.unit_price" → "<key>.unit_price"). */
export function serverErrors(fields: unknown, keys: string[]): EditorErrors {
  if (typeof fields !== 'object' || fields === null) return {}
  const errors: EditorErrors = {}
  for (const [name, message] of Object.entries(fields)) {
    if (typeof message !== 'string') continue
    const match = /^lines\.(\d+)\.(\w+)$/.exec(name)
    const key = match ? keys[Number(match[1])] : undefined
    errors[match && key ? `${key}.${match[2]}` : name] = message
  }
  return errors
}

/** Moves the line at `from` to `to` (both indexes in the current order). */
export function moveLine(lines: EditorLine[], from: number, to: number) {
  if (from === to || to < 0 || to >= lines.length) return lines
  const next = [...lines]
  const [line] = next.splice(from, 1)
  if (line) next.splice(to, 0, line)
  return next
}

/** Switching how prices treat VAT: "none" makes every line "not subject", back gives the default. */
export function changeVatMode(
  values: EditorValues,
  mode: VatMode,
  defaultRate: string,
): EditorValues {
  return {
    ...values,
    vat_mode: mode,
    lines: values.lines.map((line) =>
      mode === 'none'
        ? {
            ...line,
            vat_category: 'O',
            vat_rate: '0',
            vat_exemption_code: defaultExemptionCode('O'),
          }
        : line.vat_category === 'O'
          ? { ...line, vat_category: 'S', vat_rate: defaultRate, vat_exemption_code: null }
          : line,
    ),
  }
}

/** The editor's control for a cannot-issue reason's field ("lines.2.quantity", "due_date"). */
export function reasonTarget(field: string | undefined): { field: string; line?: number } | null {
  if (!field) return null
  const line = /^lines\.(\d+)\.(\w+)$/.exec(field)
  if (line) return { field: line[2] ?? 'description', line: Number(line[1]) }
  if (field === 'lines') return { field: 'add-line' }
  if (field === 'issue_date' || field === 'due_date' || field === 'currency') return { field }
  return null
}

/** A credit note keeps the invoice's client, currency, VAT mode and discount: never sent. */
export function withoutCreditLocks(input: Partial<InvoiceInput>): Partial<InvoiceInput> {
  const copy = { ...input }
  delete copy.client_id
  delete copy.currency
  delete copy.vat_mode
  delete copy.discount_percent
  delete copy.payment_methods
  return copy
}

/** Fields a kind never sends: a credit note's locks; proforma and self-billed have no payment methods. */
export function lockedInput(
  kind: InvoiceKind,
  input: Partial<InvoiceInput>,
): Partial<InvoiceInput> {
  if (kind === 'credit_note') return withoutCreditLocks(input)
  if (kind !== 'proforma' && kind !== 'self_billed') return input
  const copy = { ...input }
  delete copy.payment_methods
  return copy
}

/**
 * A catalogue item as a line: it replaces the sheet's only line while that is untouched, else it
 * goes at the end. Returns the lines and the new line's key (to focus its quantity).
 */
export function addPickedLine(
  lines: EditorLine[],
  picked: Pick<
    LineInput,
    'description' | 'quantity' | 'unit' | 'unit_price' | 'vat_category' | 'vat_rate'
  >,
  vatMode: VatMode,
  defaultRate: string,
): { lines: EditorLine[]; key: string } {
  const line: EditorLine = {
    ...newLine({ vat_mode: vatMode }, defaultRate),
    ...picked,
    // The editor shows rates as typed ("8.1", not "8.10").
    vat_rate: trimFractionZeros(picked.vat_rate),
  }
  const only = lines.length === 1 ? lines[0] : undefined
  return {
    lines: only && isBlankLine(only) ? [line] : [...lines, line],
    key: line.key,
  }
}

/** Why the schedule stops issuing ("Off by 39.65"), or null when it may be issued. */
export function scheduleBlocker(
  values: Pick<EditorValues, 'kind' | 'instalments' | 'issue_date' | 'currency'>,
  payable: string | null,
  generated: InstalmentRow[],
): string | null {
  const schedule = values.instalments
  if (!schedule || !isReceivable(values.kind)) return null
  const rows = schedule.items ?? generated
  if (rows.some((row) => row.due_date < values.issue_date))
    return translate('anInstalmentIsDueBeforeTheIssueDate')
  const gap = schedule.items && payable !== null ? instalmentGap(rows, payable) : null
  return gap ? translate('offBy', { value1: formatAmount(gap) }) : null
}
